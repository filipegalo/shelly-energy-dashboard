func postgresStatement(statement string) string {
	statement = strings.TrimSpace(statement)
	if statement == "" || strings.HasPrefix(statement, "PRAGMA") {
		return ""
	}
	statement = strings.ReplaceAll(statement, "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
	statement = strings.ReplaceAll(statement, " COLLATE NOCASE", "")
	statement = strings.ReplaceAll(statement, " CHECK (json_valid(capabilities_json))", "")
	statement = strings.ReplaceAll(statement, " CHECK (json_valid(details_json))", "")
	statement = strings.ReplaceAll(statement, " CHECK (raw_device_info IS NULL OR json_valid(raw_device_info))", "")
	statement = strings.ReplaceAll(statement, " CHECK (raw_status IS NULL OR json_valid(raw_status))", "")
	statement = strings.ReplaceAll(statement, "INSERT OR IGNORE", "INSERT")
	statement = strings.ReplaceAll(statement, "UPDATE OR IGNORE", "UPDATE")
	stamp := "to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')"
	statement = strings.ReplaceAll(statement, "datetime('now')", stamp)
	statement = strings.ReplaceAll(statement, "strftime('%Y-%m-%dT%H:%M:%fZ','now')", stamp)
	if strings.HasPrefix(statement, "INSERT INTO") {
		statement += " ON CONFLICT DO NOTHING"
	}
	return statement
}

